#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const defaultDistDirectory = resolve(scriptDirectory, '..', 'dist');

async function listFiles(directory, root = directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) files.push(...await listFiles(path, root));
    else files.push(relative(root, path).split(sep).join('/'));
  }
  return files;
}

function workerSource({ cacheId, precache, hashedAssets }) {
  return `/* Generated by scripts/generate-service-worker.mjs. Do not edit. */
const CACHE_NAME = ${JSON.stringify(`lightweaver-shell-${cacheId}`)};
const PRECACHE = ${JSON.stringify(precache)};
const HASHED_ASSETS = new Set(${JSON.stringify(hashedAssets)});

self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE_NAME).then(cache => cache.addAll(PRECACHE)));
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    for (const name of await caches.keys()) {
      if (name.startsWith('lightweaver-shell-') && name !== CACHE_NAME) await caches.delete(name);
    }
    await self.clients.claim();
  })());
});

self.addEventListener('message', event => {
  if (event.data?.type === 'SKIP_WAITING') self.skipWaiting();
});

async function cacheFirst(request) {
  const cache = await caches.open(CACHE_NAME);
  return (await cache.match(request)) || fetch(request);
}

async function networkFirst(request, fallbackPath) {
  const cache = await caches.open(CACHE_NAME);
  try {
    const response = await fetch(request, { cache: 'no-store' });
    if (response.ok) await cache.put(request, response.clone());
    return response;
  } catch (error) {
    const fallback = await cache.match(request) || await cache.match(fallbackPath);
    if (fallback) return fallback;
    throw error;
  }
}

self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin || url.pathname.startsWith('/api/')) return;
  if (request.mode === 'navigate') {
    event.respondWith(networkFirst(request, '/index.html'));
    return;
  }
  if (url.pathname === '/studio-release.json') {
    event.respondWith(networkFirst(request, '/studio-release.json'));
    return;
  }
  if (HASHED_ASSETS.has(url.pathname) || url.pathname === '/manifest.webmanifest' || url.pathname.startsWith('/fonts/')) {
    event.respondWith(cacheFirst(request));
  }
});
`;
}

export async function generateServiceWorker({ distDir = defaultDistDirectory } = {}) {
  const directory = resolve(distDir);
  const files = (await listFiles(directory)).filter(file => file !== 'sw.js');
  const hashedAssets = files
    .filter(file => /^assets\/.+-[A-Za-z0-9_-]{8,}\.[^.]+$/.test(file))
    .map(file => `/${file}`)
    .sort();
  const localShell = files
    .filter(file => file === 'index.html' || file === 'manifest.webmanifest' || file.startsWith('fonts/'))
    .map(file => `/${file}`);
  const precache = [...new Set(['/index.html', '/studio-release.json', ...localShell, ...hashedAssets])].sort();
  const release = JSON.parse(await readFile(resolve(directory, 'studio-release.json'), 'utf8'));
  const cacheId = createHash('sha256')
    .update(JSON.stringify({ buildId: release.buildId, buildNumber: release.buildNumber, precache }))
    .digest('hex')
    .slice(0, 20);
  await writeFile(resolve(directory, 'sw.js'), workerSource({ cacheId, precache, hashedAssets }));
  return { cacheId, precache, hashedAssets };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const result = await generateServiceWorker({ distDir: process.argv[2] || defaultDistDirectory });
  process.stdout.write(`${JSON.stringify(result)}\n`);
}
