#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { brotliCompressSync, constants as zlibConstants, gzipSync } from 'node:zlib';
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { resolveStudioReleaseIdentity } from './studio-release-identity.mjs';

const scriptsDirectory = dirname(fileURLToPath(import.meta.url));
const projectDirectory = resolve(scriptsDirectory, '..');
const repositoryRoot = resolve(projectDirectory, '..');
export const DEFAULT_CARD_STUDIO_MAXIMUM_BYTES = 2_500_000;
export const CARD_STUDIO_FIRMWARE_API = Object.freeze({ min: 2, max: 2 });

export function resolveCardStudioReleaseIdentity(identity, env = process.env) {
  return {
    buildId: identity.sourceRevision,
    buildNumber: identity.buildNumber,
    projectSchema: {
      min: Number(env.LW_PROJECT_SCHEMA_MIN || 3),
      max: Number(env.LW_PROJECT_SCHEMA_MAX || 3),
    },
    // This is the card's compiled LW_CAPABILITIES_VERSION contract, not a
    // caller-selectable compatibility hint. Changing it requires changing the
    // firmware capability version and its release contracts together.
    firmwareApi: { ...CARD_STUDIO_FIRMWARE_API },
  };
}

const MIME_TYPES = Object.freeze({
  '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8', '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml', '.png': 'image/png', '.webp': 'image/webp',
  '.woff2': 'font/woff2', '.webmanifest': 'application/manifest+json',
});

async function walk(directory, root = directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(path, root));
    else files.push({ path, file: relative(root, path).split(sep).join('/') });
  }
  return files;
}

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

function mimeType(file) {
  const extension = file.slice(file.lastIndexOf('.'));
  return MIME_TYPES[extension] || 'application/octet-stream';
}

function assertIdentity(identity) {
  if (!/^[a-f0-9]{40}$/.test(identity?.buildId || '')) throw new Error('card Studio buildId must be a 40-character lowercase Git revision');
  if (!Number.isInteger(identity?.buildNumber) || identity.buildNumber < 1) throw new Error('card Studio buildNumber must be positive');
  for (const rangeName of ['projectSchema', 'firmwareApi']) {
    const range = identity?.[rangeName];
    if (!Number.isInteger(range?.min) || !Number.isInteger(range?.max) || range.min < 1 || range.max < range.min) {
      throw new Error(`${rangeName} must be a positive compatible range`);
    }
  }
}

function assertSafeBuiltAsset(file, bytes) {
  if (file.endsWith('.map')) throw new Error(`card Studio source map is forbidden: ${file}`);
  if (/\.(?:html|css|js|json|svg)$/.test(file)) {
    const source = bytes.toString('utf8');
    if (/sourceMappingURL\s*=/.test(source)) throw new Error(`card Studio source map reference is forbidden: ${file}`);
    if (/(?:src|href)\s*=\s*["']https?:\/\/|url\(\s*["']?https?:\/\//i.test(source)) {
      throw new Error(`card Studio external asset URL is forbidden: ${file}`);
    }
  }
}

function byteArray(name, bytes) {
  const rows = [];
  for (let index = 0; index < bytes.length; index += 16) {
    rows.push(`  ${[...bytes.subarray(index, index + 16)].map(value => `0x${value.toString(16).padStart(2, '0')}`).join(', ')},`);
  }
  return `static const uint8_t ${name}[] PROGMEM = {\n${rows.join('\n')}\n};`;
}

function cppString(value) {
  return JSON.stringify(String(value)).replace(/\\u2028|\\u2029/g, '');
}

function generateHeader(release, embedded) {
  const arrays = embedded.map((asset, index) => byteArray(`LW_CARD_STUDIO_ASSET_${index}_BYTES`, asset.bytes));
  const rows = embedded.map((asset, index) => `  { ${cppString(asset.route)}, ${cppString(asset.contentType)}, "br", LW_CARD_STUDIO_ASSET_${index}_BYTES, ${asset.bytes.byteLength}u, ${asset.originalSize}u, ${cppString(asset.sha256)}, ${asset.immutable ? 'true' : 'false'} },`);
  return `// Generated by lightweaver/scripts/build-card-studio.mjs. Do not edit.
#pragma once
#include <stddef.h>
#include <stdint.h>
#include <pgmspace.h>

struct LightweaverCardStudioAsset {
  const char* path;
  const char* contentType;
  const char* contentEncoding;
  const uint8_t* bytes;
  size_t compressedSize;
  size_t uncompressedSize;
  const char* compressedSha256;
  bool immutable;
};

static const char LW_CARD_STUDIO_BUILD_ID[] = ${cppString(release.buildId)};
static const uint32_t LW_CARD_STUDIO_BUILD_NUMBER = ${release.buildNumber}u;
static const uint32_t LW_CARD_STUDIO_PROJECT_SCHEMA_MIN = ${release.projectSchema.min}u;
static const uint32_t LW_CARD_STUDIO_PROJECT_SCHEMA_MAX = ${release.projectSchema.max}u;
static const uint32_t LW_CARD_STUDIO_FIRMWARE_API_MIN = ${release.firmwareApi.min}u;
static const uint32_t LW_CARD_STUDIO_FIRMWARE_API_MAX = ${release.firmwareApi.max}u;
static const size_t LW_CARD_STUDIO_TOTAL_SIZE = ${release.totalSize}u;
static const char LW_CARD_STUDIO_BUNDLE_SHA256[] = ${cppString(release.bundleSha256)};
static const size_t LW_CARD_STUDIO_ASSET_COUNT = ${embedded.length}u;

${arrays.join('\n\n')}

static const LightweaverCardStudioAsset LW_CARD_STUDIO_ASSETS[] PROGMEM = {
${rows.join('\n')}
};
`;
}

export async function packageCardStudio({ rawDir, outputDir, headerPath, identity, maximumBytes = DEFAULT_CARD_STUDIO_MAXIMUM_BYTES }) {
  assertIdentity(identity);
  const sourceDirectory = resolve(rawDir);
  const destination = resolve(outputDir);
  const files = (await walk(sourceDirectory))
    .filter(entry => !entry.file.startsWith('.vite/'))
    .map(entry => entry.file === 'card.html' ? { ...entry, file: 'index.html' } : entry);
  if (!files.some(entry => entry.file === 'index.html')) throw new Error('card Studio build is missing index.html');
  await rm(destination, { recursive: true, force: true });
  await mkdir(destination, { recursive: true });

  const assets = [];
  const embedded = [];
  for (const entry of files) {
    const original = await readFile(entry.path);
    assertSafeBuiltAsset(entry.file, original);
    const brotli = brotliCompressSync(original, { params: { [zlibConstants.BROTLI_PARAM_QUALITY]: 11 } });
    const gzip = gzipSync(original, { level: 9, mtime: 0 });
    const outputPath = resolve(destination, entry.file);
    await mkdir(dirname(outputPath), { recursive: true });
    await writeFile(outputPath, original);
    await writeFile(`${outputPath}.br`, brotli);
    await writeFile(`${outputPath}.gz`, gzip);
    const route = entry.file === 'index.html' ? '/studio/' : `/studio/${entry.file}`;
    const item = {
      file: entry.file, route, contentType: mimeType(entry.file),
      immutable: entry.file !== 'index.html' && /-[A-Za-z0-9_-]{8,}\./.test(entry.file),
      original: { size: original.byteLength, sha256: sha256(original) },
      brotli: { size: brotli.byteLength, sha256: sha256(brotli) },
      gzip: { size: gzip.byteLength, sha256: sha256(gzip) },
    };
    assets.push(item);
    embedded.push({ ...item, bytes: brotli, originalSize: original.byteLength, sha256: item.brotli.sha256 });
  }
  const totalSize = embedded.reduce((sum, asset) => sum + asset.bytes.byteLength, 0);
  if (totalSize > maximumBytes) throw new Error(`card Studio bundle ${totalSize} bytes exceeds maximum bundle size ${maximumBytes}`);
  const bundleSha256 = sha256(Buffer.from(assets.map(asset => `${asset.route}\0${asset.brotli.sha256}\0${asset.brotli.size}\n`).join('')));
  const release = {
    schemaVersion: 1,
    target: 'card-local',
    buildId: identity.buildId,
    buildNumber: identity.buildNumber,
    projectSchema: identity.projectSchema,
    firmwareApi: identity.firmwareApi,
    compression: 'br',
    totalSize,
    maximumSize: maximumBytes,
    bundleSha256,
    assets,
  };
  await writeFile(resolve(destination, 'card-studio-release.json'), `${JSON.stringify(release, null, 2)}\n`);
  await mkdir(dirname(resolve(headerPath)), { recursive: true });
  await writeFile(resolve(headerPath), generateHeader(release, embedded));
  return { release, headerPath: resolve(headerPath) };
}

// The canonical build exists so "did this change the card-embedded Studio?"
// has a byte-level answer. Pinning the release identity removes the only
// revision-dependent input, so two revisions produce the same bundleSha256
// exactly when the embedded Studio they would ship is the same. The pinned
// values are impossible for a real release (a zero revision, build 1).
export const CANONICAL_CARD_BUNDLE_IDENTITY = Object.freeze({
  sourceRevision: '0'.repeat(40),
  buildNumber: 1,
});

async function main() {
  const canonical = process.argv.includes('--canonical');
  const identityEnv = canonical
    ? {
      ...process.env,
      LIGHTWEAVER_SOURCE_REVISION: CANONICAL_CARD_BUNDLE_IDENTITY.sourceRevision,
      LIGHTWEAVER_BUILD_NUMBER: String(CANONICAL_CARD_BUNDLE_IDENTITY.buildNumber),
    }
    : process.env;
  const identity = resolveStudioReleaseIdentity({ cwd: projectDirectory, env: identityEnv });
  const rawDir = resolve(projectDirectory, canonical ? '.card-dist-raw-canonical' : '.card-dist-raw');
  execFileSync(resolve(projectDirectory, 'node_modules', '.bin', 'vite'), ['build', '--mode', 'card'], {
    cwd: projectDirectory,
    stdio: canonical ? 'ignore' : 'inherit',
    env: { ...identityEnv, LW_CARD_STUDIO_BUILD: '1', LW_CARD_STUDIO_RAW_DIR: rawDir },
  });
  const result = await packageCardStudio({
    rawDir,
    outputDir: resolve(projectDirectory, canonical ? '.card-dist-canonical' : 'card-dist'),
    headerPath: canonical
      ? resolve(projectDirectory, '.card-dist-canonical', 'LightweaverCardStudioBundle.h')
      : resolve(repositoryRoot, 'firmware', 'lightweaver-controller', 'src', 'LightweaverCardStudioBundle.h'),
    identity: resolveCardStudioReleaseIdentity(identity, identityEnv),
    maximumBytes: Number(process.env.LW_CARD_STUDIO_MAX_BYTES || DEFAULT_CARD_STUDIO_MAXIMUM_BYTES),
  });
  process.stdout.write(`${JSON.stringify(canonical
    ? { canonical: true, bundleSha256: result.release.bundleSha256, totalSize: result.release.totalSize }
    : result.release)}\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await main();
